create table public.push_subscriptions_general (
    id bigint generated by default as identity primary key,
    endpoint text not null unique,
    subscription jsonb not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.push_subscriptions_general enable row level security;

revoke all on table public.push_subscriptions_general from public, anon, authenticated;
grant all on table public.push_subscriptions_general to service_role;
